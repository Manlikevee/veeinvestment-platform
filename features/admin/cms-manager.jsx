"use client";

import { useState } from "react";
import { Eye, FilePlus2, Globe, Plus } from "lucide-react";
import Link from "next/link";
import { PageHeader } from "@/components/ui/page-header";
import { StatCard } from "@/components/ui/stat-card";
import { DataTable } from "@/components/ui/data-table";
import { StatusBadge } from "@/components/ui/status-badge";
import { Modal } from "@/components/ui/modal";
import { Input, Select } from "@/components/ui/form-field";
import { useToast } from "@/providers/toast-provider";
import { cmsPages as seedPages } from "@/lib/data/admin";
import { formatDate } from "@/lib/utils/format";

export function CmsManager() {
  const [pages, setPages] = useState(seedPages);
  const [open, setOpen] = useState(false);
  const [form, setForm] = useState({ title: "", type: "Page", slug: "" });
  const { toast } = useToast();

  function create(event) {
    event.preventDefault();
    if (!form.title.trim()) return;
    setPages((current) => [{ id: `CMS-${String(current.length + 10)}`, title: form.title, type: form.type, slug: form.slug || `/${form.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`, status: "Draft", updated: new Date().toISOString().slice(0, 10), author: "Ngozi Eze", sections: 0 }, ...current]);
    setOpen(false); setForm({ title: "", type: "Page", slug: "" });
    toast({ title: "CMS draft created in this demonstration", message: "No public page was created or published.", tone: "info" });
  }

  function togglePublish(row) {
    setPages((current) => current.map((page) => page.id === row.id ? { ...page, status: page.status === "Published" ? "Draft" : "Published" } : page));
    toast({ title: "Publishing state staged", message: "Public content would require approval and cache invalidation in a live system.", tone: "info" });
  }

  const columns = [
    { key: "title", header: "Content", sortable: true, render: (row) => <div className="table-primary-copy"><strong>{row.title}</strong><span>{row.slug} · {row.type}</span></div> },
    { key: "status", header: "Status", sortable: true, render: (row) => <StatusBadge status={row.status} /> },
    { key: "author", header: "Author", render: (row) => row.author, hideOnMobile: true },
    { key: "sections", header: "Sections", align: "right", render: (row) => row.sections, hideOnMobile: true },
    { key: "updated", header: "Updated", sortable: true, render: (row) => formatDate(row.updated), hideOnMobile: true },
    { key: "actions", header: "", exportable: false, align: "right", render: (row) => <div className="flex" style={{ gap: 4, justifyContent: "flex-end" }}>{row.slug.startsWith("/") ? <Link href={row.slug} className="icon-button" aria-label="Preview page"><Eye size={14} /></Link> : null}<button type="button" className="btn btn-outline btn-sm" onClick={() => togglePublish(row)}>{row.status === "Published" ? "Unpublish" : "Publish"}</button></div> },
  ];

  return (
    <div className="app-page">
      <PageHeader eyebrow="Content operations" title="Content management" description="Manage public pages, insights, legal documents, homepage sections and publication state." actions={<button type="button" className="btn btn-primary" onClick={() => setOpen(true)}><Plus size={16} /> New content</button>} />
      <div className="stat-grid" style={{ marginBottom: 16 }}>
        <StatCard label="Content items" value={pages.length} detail="In this demonstration" icon="newspaper" tone="emerald" />
        <StatCard label="Published" value={pages.filter((p) => p.status === "Published").length} detail="Visible content" icon="globe" tone="forest" />
        <StatCard label="Drafts" value={pages.filter((p) => p.status === "Draft").length} detail="Awaiting review" icon="file-text" tone="sand" />
        <StatCard label="Scheduled" value={pages.filter((p) => p.status === "Scheduled").length} detail="Queued publication" icon="calendar" tone="sage" />
      </div>
      <DataTable columns={columns} rows={pages} searchPlaceholder="Search content…" searchKeys={["title", "slug", "type", "status", "author"]} filters={[{ key: "status", label: "Status", options: ["Published", "Draft", "Scheduled"] }, { key: "type", label: "Type", options: ["Landing page", "Page", "Catalogue", "Insight", "Legal", "Component"] }]} exportName="vee-cms-pages" footerNote="Demonstration content inventory" />
      <div className="info-note is-warning" style={{ marginTop: 14 }}><FilePlus2 size={15} /><span>Publishing financial product or legal content must require approval. Public pages must not be changed without version history and cache invalidation.</span></div>
      <Modal open={open} onClose={() => setOpen(false)} title="Create content" description="Create a draft page. No public content is generated by this demonstration." footer={<><button type="button" className="btn btn-ghost" onClick={() => setOpen(false)}>Cancel</button><button type="submit" form="cms-form" className="btn btn-primary">Create draft</button></>}>
        <form id="cms-form" className="stack" onSubmit={create}><Input label="Title" name="cmsTitle" value={form.title} onChange={(event) => setForm((c) => ({ ...c, title: event.target.value }))} required /><Select label="Content type" name="cmsType" value={form.type} onChange={(event) => setForm((c) => ({ ...c, type: event.target.value }))} options={["Page", "Insight", "Legal", "Landing page"]} /><Input label="Slug (optional)" name="cmsSlug" value={form.slug} onChange={(event) => setForm((c) => ({ ...c, slug: event.target.value }))} placeholder="/about" /></form>
      </Modal>
    </div>
  );
}
